/**
 * Defines each logo once for the whole page; TechIcon points at these with
 * <use>. A server component, so the logos' SVG reaches the page as HTML and
 * never as JavaScript. Render it once, anywhere on the page.
 */
export default function TechIconSprite() {
  return (
    <svg aria-hidden="true" width="0" height="0" className="absolute">
      {(Object.entries(LOGOS) as [TechIconId, IconType][]).map(([id, Logo]) => (
        <symbol key={id} id={spriteId(id)}>
          <Logo size="100%" />
        </symbol>
      ))}
    </svg>
  );
}
